package wsclient

import (
	"fmt"
	"strings"
)

// RenderPAC builds a PAC script that sends the listed domains through this
// client's local inbound and everything else through fallback.
//
// PAC has no way to mean "use the system proxy": the supported return values are
// only DIRECT / PROXY host:port / HTTPS host:port / SOCKS4 / SOCKS5. So fallback
// must name a concrete proxy, or DIRECT when the caller passes "".
//
// The domain match is a manual suffix comparison rather than dnsDomainIs() or
// shExpMatch(): the former misses the apex domain on some implementations and
// the latter both misses it and lets "example.org.evil.com" through. dnsResolve()
// and isInNet() are deliberately absent — under a fake-IP resolver they always
// lie.
func RenderPAC(httpPort, socksPort int, domains []string, fallback string) string {
	tunnel := fmt.Sprintf("PROXY 127.0.0.1:%d", httpPort)
	if socksPort > 0 {
		tunnel += fmt.Sprintf("; SOCKS5 127.0.0.1:%d", socksPort)
	}
	tunnel += "; DIRECT"

	system := strings.TrimSpace(fallback)
	if system == "" {
		system = "DIRECT"
	} else if !strings.HasPrefix(system, "PROXY ") && !strings.HasPrefix(system, "SOCKS") &&
		!strings.HasPrefix(system, "HTTPS ") && system != "DIRECT" {
		system = "PROXY " + system
	}

	var b strings.Builder
	b.WriteString("// Generated by ai-critic ws-proxy client.\n")
	b.WriteString("// Domains below go through the local WS tunnel; the rest use the fallback proxy.\n")
	b.WriteString("// PAC has no \"system proxy\" value, so the fallback is spelled out explicitly.\n\n")
	b.WriteString(fmt.Sprintf("var TUNNEL_PROXY = %q;\n", tunnel))
	b.WriteString(fmt.Sprintf("var FALLBACK_PROXY = %q;\n", system))
	b.WriteString("var TUNNEL_DOMAINS = [")
	for i, d := range domains {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("%q", strings.ToLower(strings.TrimSpace(d))))
	}
	b.WriteString("];\n\n")
	b.WriteString(`function FindProxyForURL(url, host) {
  if (isPlainHostName(host)) return "DIRECT";
  if (host === "127.0.0.1" || host === "::1" || host === "localhost") return "DIRECT";
  if (TUNNEL_DOMAINS.length === 0) return TUNNEL_PROXY;
  if (inDomains(host, TUNNEL_DOMAINS)) return TUNNEL_PROXY;
  return FALLBACK_PROXY;
}

// Match the apex domain and every subdomain, but not notexample.com and not
// example.com.evil.com.
function inDomains(host, domains) {
  var h = host.toLowerCase();
  for (var i = 0; i < domains.length; i++) {
    var d = domains[i];
    if (h === d) return true;
    if (h.length > d.length && h.substring(h.length - d.length - 1) === "." + d) return true;
  }
  return false;
}
`)
	return b.String()
}
